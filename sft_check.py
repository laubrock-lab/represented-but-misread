"""What do the SFT data teach about our three judgments? (No download of the mixtures.)

Uses the Hugging Face dataset server (public mixtures; nothing of ours is sent):
  1. random sample: N_OFFSETS random offsets x BLOCK rows per mixture (/rows endpoint),
     to estimate base rates of task types;
  2. full-text search over ALL rows (/search endpoint, BM25 index of the server) for
     rare task types, with total hit counts and up to MAX_HITS hits stored for coding.

Mixtures: OLMo 2 SFT = allenai/tulu-3-sft-olmo-2-mixture (model card); Apertus 1.5 SFT =
swiss-ai/Apertus-v1.5-SFT-mix (assumed from name/version; the model card is gated).

Usage:  python sft_check.py --census          (preferred: full pass, exact regex counts)
        python sft_check.py [--sample] [--search]   (dataset-server API; rate-limited)
Output: outputs/sft_check/{<mixture>_sample.jsonl, <mixture>_hits.jsonl, search_counts.csv}
        (gitignored; public data under ODC-BY / the mixtures' licenses)
"""
from __future__ import annotations

import argparse
import json
import random
import time

import pandas as pd
import requests

import config

API = "https://datasets-server.huggingface.co"
MIXTURES = {"tulu3_olmo2": "allenai/tulu-3-sft-olmo-2-mixture",
            "apertus15": "swiss-ai/Apertus-v1.5-SFT-mix"}
QUERIES = {
    "authorship": ["AI-generated", "written by AI", "written by an AI", "generated by AI",
                   "written by a human", "human-written", "AI detector", "AI detection",
                   "generated by ChatGPT", "written by ChatGPT"],
    "deception": ["fake review", "fake reviews", "deceptive review", "genuine review",
                  "deceptive", "deception detection", "is lying", "fake or real"],
    "truth": ["true or false", "true/false", "is this statement true", "fact-check",
              "is the following statement true"],
}
OUT = config.OUTPUT_DIR / "sft_check"


def get(path: str, **params) -> dict:
    """GET with retries: the server answers 429 / HTML / {"error": ...} when busy."""
    err = None
    for attempt in range(10):
        time.sleep(0.3)
        try:
            r = requests.get(f"{API}/{path}", params=params, timeout=90)
            d = r.json()
            if r.status_code == 200 and "error" not in d:
                return d
            err = d.get("error", r.status_code)
        except (requests.RequestException, ValueError) as e:
            err = repr(e)[:200]
        time.sleep(min(10 * (attempt + 1), 60))
    raise RuntimeError(f"{path} {params}: {err}")


def n_rows(ds: str) -> int:
    d = get("size", dataset=ds)
    return sum(s["num_rows"] for s in d["size"]["splits"] if s["split"] == "train")


def sample(name: str, ds: str, n_offsets: int, block: int, seed: int = 1) -> None:
    n = n_rows(ds)
    rng = random.Random(seed)
    with open(OUT / f"{name}_sample.jsonl", "w") as f:
        for off in sorted(rng.sample(range(n - block), n_offsets)):
            for row in get("rows", dataset=ds, config="default", split="train",
                           offset=off, length=block)["rows"]:
                f.write(json.dumps(row["row"], ensure_ascii=False) + "\n")
    print(f"{name}: sampled {n_offsets * block} of {n} rows")


def search(name: str, ds: str, max_hits: int) -> list[dict]:
    counts = []
    with open(OUT / f"{name}_hits.jsonl", "w") as f:
        for cat, qs in QUERIES.items():
            for q in qs:
                d = get("search", dataset=ds, config="default", split="train", query=q, length=100)
                total = d["num_rows_total"]
                counts.append(dict(mixture=name, category=cat, query=q, hits=total))
                rows, off = d["rows"], 100
                while off < min(total, max_hits):
                    rows += get("search", dataset=ds, config="default", split="train", query=q,
                                offset=off, length=100)["rows"]
                    off += 100
                for r in rows:
                    f.write(json.dumps(dict(category=cat, query=q, **r["row"]), ensure_ascii=False) + "\n")
                print(f"{name:12s} {cat:10s} {q!r:32s} {total}")
    return counts


