"""What do the SFT data teach about our three judgments? (No download of the mixtures.)

Uses the Hugging Face dataset server (public mixtures; nothing of ours is sent):
  1. random sample: N_OFFSETS random offsets x BLOCK rows per mixture (/rows endpoint),
     to estimate base rates of task types;
  2. full-text search over ALL rows (/search endpoint, BM25 index of the server) for
     rare task types, with total hit counts and up to MAX_HITS hits stored for coding.

Mixtures: OLMo 2 SFT = allenai/tulu-3-sft-olmo-2-mixture (model card); Apertus 1.5 SFT =
swiss-ai/Apertus-v1.5-SFT-mix (assumed from name/version; the model card is gated).

Usage:  python sft_check.py --census          (preferred: full pass, exact regex counts)
        python sft_check.py [--sample] [--search]   (dataset-server API; rate-limited)
Output: outputs/sft_check/{<mixture>_sample.jsonl, <mixture>_hits.jsonl, search_counts.csv}
        (gitignored; public data under ODC-BY / the mixtures' licenses)
"""
from __future__ import annotations

import argparse
import json
import random
import time

import pandas as pd
import requests

import config

API = "https://datasets-server.huggingface.co"
MIXTURES = {"tulu3_olmo2": "allenai/tulu-3-sft-olmo-2-mixture",
            "apertus15": "swiss-ai/Apertus-v1.5-SFT-mix"}
QUERIES = {
    "authorship": ["AI-generated", "written by AI", "written by an AI", "generated by AI",
                   "written by a human", "human-written", "AI detector", "AI detection",
                   "generated by ChatGPT", "written by ChatGPT"],
    "deception": ["fake review", "fake reviews", "deceptive review", "genuine review",
                  "deceptive", "deception detection", "is lying", "fake or real"],
    "truth": ["true or false", "true/false", "is this statement true", "fact-check",
              "is the following statement true"],
}
PARQUET_SPLIT = {"tulu3_olmo2": "train", "apertus15": "partial-train"}
OUT = config.OUTPUT_DIR / "sft_check"


def get(path: str, **params) -> dict:
    """GET with retries: the server answers 429 / HTML / {"error": ...} when busy."""
    err = None
    for attempt in range(10):
        time.sleep(0.3)
        try:
            r = requests.get(f"{API}/{path}", params=params, timeout=90)
            d = r.json()
            if r.status_code == 200 and "error" not in d:
                return d
            err = d.get("error", r.status_code)
        except (requests.RequestException, ValueError) as e:
            err = repr(e)[:200]
        time.sleep(min(10 * (attempt + 1), 60))
    raise RuntimeError(f"{path} {params}: {err}")


def n_rows(ds: str) -> int:
    d = get("size", dataset=ds)
    return sum(s["num_rows"] for s in d["size"]["splits"] if s["split"] == "train")


def sample(name: str, ds: str, n_offsets: int, block: int, seed: int = 1) -> None:
    n = n_rows(ds)
    rng = random.Random(seed)
    with open(OUT / f"{name}_sample.jsonl", "w") as f:
        for off in sorted(rng.sample(range(n - block), n_offsets)):
            for row in get("rows", dataset=ds, config="default", split="train",
                           offset=off, length=block)["rows"]:
                f.write(json.dumps(row["row"], ensure_ascii=False) + "\n")
    print(f"{name}: sampled {n_offsets * block} of {n} rows")


def search(name: str, ds: str, max_hits: int) -> list[dict]:
    counts = []
    with open(OUT / f"{name}_hits.jsonl", "w") as f:
        for cat, qs in QUERIES.items():
            for q in qs:
                d = get("search", dataset=ds, config="default", split="train", query=q, length=100)
                total = d["num_rows_total"]
                counts.append(dict(mixture=name, category=cat, query=q, hits=total))
                rows, off = d["rows"], 100
                while off < min(total, max_hits):
                    rows += get("search", dataset=ds, config="default", split="train", query=q,
                                offset=off, length=100)["rows"]
                    off += 100
                for r in rows:
                    f.write(json.dumps(dict(category=cat, query=q, **r["row"]), ensure_ascii=False) + "\n")
                print(f"{name:12s} {cat:10s} {q!r:32s} {total}")
    return counts


# --------------------------------------------------------------------------- census
# Full pass over every row (streaming; nothing stored except the matching examples).
import re  # noqa: E402

AI_REF = r"(?:AI|A\.I\.|artificial intelligence|(?:a |an )?(?:large )?language model|LLM|chatbot|ChatGPT|GPT-?\d?|machine)"
PATTERNS = {
    # mention of AI vs. human authorship of a text
    "authorship_mention": re.compile(
        rf"\b(?:written|generated|produced|authored|created) by (?:an? )?(?:{AI_REF}|(?:a )?human)\b"
        rf"|\b(?:AI|machine)[- ]generated\b|\bhuman[- ]written\b|\bAI[- ](?:text )?detect", re.I),
    # an explicit judgment request: was this written by AI / a human?
    "authorship_task": re.compile(
        rf"\b(?:is|was|were) (?:this|the following|these|it) (?:text|essay|passage|article|paragraph|message|review|poem|story|response)?\s*"
        rf"(?:written|generated|produced) by (?:an? )?(?:{AI_REF}|human|person)"
        rf"|\b(?:determine|decide|classify|detect|identify|tell)\b[^.?!\n]{{0,80}}\b(?:AI|machine)[- ]generated"
        rf"|\b(?:human|AI)[- ](?:written|generated) or (?:AI|human|machine)[- ](?:written|generated)", re.I),
    "deception": re.compile(
        r"\bfake reviews?\b|\bdeceptive (?:review|opinion|statement)s?\b|\bgenuine or fake\b|\bfake or (?:real|genuine)\b"
        r"|\bopinion spam\b|\bdeception detection\b|\bis (?:he|she|the (?:speaker|person|witness)) lying\b", re.I),
    "truefalse_task": re.compile(
        r"\btrue or false\b|\btrue/false\b|\b(?:is|are) (?:this|the following) (?:statement|claim|sentence)s? (?:true|correct|accurate|factual)",
        re.I),
}
NEG = re.compile(r"\b(?:not|never|no longer|isn't|aren't|wasn't|weren't|doesn't|don't|didn't)\b", re.I)


def _text(c) -> str:
    """Plain text of a message content: str, list of parts ({'type': 'text', 'text': ...}), or dict."""
    if c is None:
        return ""
    if isinstance(c, str):
        return c
    if isinstance(c, dict):
        return _text(c.get("text") or c.get("content") or c.get("parts") or "")
    if isinstance(c, (list, tuple)):
        return "\n".join(_text(x) for x in c)
    return str(c)


def turns(row: dict) -> tuple[str, str]:
    """(all user/system text, all assistant text) for the common chat schemas."""
    msgs = row.get("messages") or row.get("conversations") or row.get("conversation")
    if isinstance(msgs, list):
        u, a = [], []
        for m in msgs:
            role = (m.get("role") or m.get("from") or "").lower()
            txt = m.get("content") if m.get("content") is not None else m.get("value", "")
            txt = _text(txt)
            (a if role in ("assistant", "gpt", "model", "bot") else u).append(txt)
        return "\n".join(u), "\n".join(a)
    strs = {k: v for k, v in row.items() if isinstance(v, str)}
    a = strs.pop("response", strs.pop("output", strs.pop("completion", "")))
    return "\n".join(strs.values()), a


def census(name: str, ds: str, max_store: int = 400, limit: int | None = None) -> dict:
    from datasets import load_dataset
    # dataset-server parquet conversion: complete for Tulu 3; for the Apertus mix the first
    # ~10 % ("partial-train") of the deterministically shuffled rows = a random sample
    split_dir = PARQUET_SPLIT[name]
    files = f"hf://datasets/{ds}@refs%2Fconvert%2Fparquet/default/{split_dir}/*.parquet"
    counts = {k: 0 for k in PATTERNS} | {"truefalse_task_negated": 0, "rows": 0}
    stored = {k: 0 for k in PATTERNS}
    with open(OUT / f"{name}_census_hits.jsonl", "w") as f:
        for i, row in enumerate(load_dataset("parquet", data_files=files, split="train", streaming=True)):
            if limit and i >= limit:
                break
            user, asst = turns(row)
            counts["rows"] += 1
            for k, pat in PATTERNS.items():
                m = pat.search(user)
                if not m:
                    continue
                counts[k] += 1
                neg = False
                if k == "truefalse_task":
                    window = user[max(0, m.start() - 300): m.end() + 300]
                    neg = bool(NEG.search(window))
                    counts["truefalse_task_negated"] += neg
                if stored[k] < max_store:
                    stored[k] += 1
                    s = max(0, m.start() - 400)
                    f.write(json.dumps(dict(category=k, idx=i, id=row.get("id") or row.get("conversation_id"),
                                            source=row.get("source") or row.get("dataset_source"),
                                            negated=neg, user=user[s: m.end() + 600],
                                            assistant=asst[:800]), ensure_ascii=False) + "\n")
            if i % 100000 == 0:
                print(f"{name}: {i} rows {counts}", flush=True)
    print(f"{name}: done {counts}", flush=True)
    return dict(mixture=name, **counts)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sample", action="store_true")
    ap.add_argument("--search", action="store_true")
    ap.add_argument("--census", action="store_true", help="full streaming pass with regex counts")
    ap.add_argument("--limit", type=int, help="census: stop after N rows (testing)")
    ap.add_argument("--n-offsets", type=int, default=400)
    ap.add_argument("--block", type=int, default=5)
    ap.add_argument("--max-hits", type=int, default=500)
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    counts = []
    for name, ds in MIXTURES.items():
        if args.sample:
            sample(name, ds, args.n_offsets, args.block)
        if args.search:
            counts += search(name, ds, args.max_hits)
        if args.census:
            row = census(name, ds, limit=args.limit)
            pd.DataFrame([row]).to_csv(OUT / f"{name}_census_counts.csv", index=False)
    if counts:
        pd.DataFrame(counts).to_csv(OUT / "search_counts.csv", index=False)


if __name__ == "__main__":
    main()
